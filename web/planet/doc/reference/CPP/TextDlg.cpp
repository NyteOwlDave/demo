/////////////////////////////////////////////////////////////////////////////
// Construction
/////////////////////////////////////////////////////////////////////////////

CTextDlg::CTextDlg( CWnd* pParent )
		 : CDialog( CTextDlg::IDD, pParent ) {

	//{{AFX_DATA_INIT(CTextDlg)
	m_sText = _T("");
	//}}AFX_DATA_INIT

	m_dwMaxChars = 0;
	m_sTitle = "";
}



/////////////////////////////////////////////////////////////////////////////
// DDX/DDV
/////////////////////////////////////////////////////////////////////////////

void CTextDlg::DoDataExchange( CDataExchange* pDX ) {

	CDialog::DoDataExchange(pDX);
	//{{AFX_DATA_MAP(CTextDlg)
	DDX_Text(pDX, IDC_TEXT, m_sText);
	//}}AFX_DATA_MAP
}




/////////////////////////////////////////////////////////////////////////////
// Initialization
/////////////////////////////////////////////////////////////////////////////

BOOL CTextDlg::OnInitDialog() {

	CEdit* pEdit;
	CDialog::OnInitDialog();

	if( m_sTitle > "" ) SetWindowText( m_sTitle );

	pEdit = (CEdit*)(GetDlgItem( IDC_TEXT ));
	pEdit->LimitText( (int)(m_dwMaxChars) );

	return TRUE;
}
